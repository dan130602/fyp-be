"""The single overall decision for a vLLM candidate against the Transformers baseline (Stage 3 follow-up D). Verification only; never part of the image; reads no reference text itself (it reads the scorer's
per-call error COUNTS).

    python tools/decision.py --jobs jobs.json --pilot pilot_calls_overlap_v1.json --runs <evaluation-engine/runs> --candidate-config <config file> --out decision.json \
        --candidate-docs D --candidate-state S --candidate-c4-docs D --baseline-docs D --baseline-state S --baseline-c4-docs D \
        --candidate-parity R --candidate-c4-parity R --baseline-parity R --baseline-c4-parity R --compare R \
        --score candidate_raw=RUN candidate_final=RUN baseline_raw=RUN baseline_final=RUN --config-compare-raw compare.json --config-compare-final compare.json \
        --plugin-test plugin_logits_test.json --probe-stock probe.json --probe-candidate probe.json \
        --capture capture.json --capture-replay capture_replay.json --package-manifest configs/third_party/meralion-3-asr-0.1.0.json

Verdicts and exit codes:  ACCEPTED 0 | REJECTED 1 (the evidence is consistent and a check fails) | NOT AN ACCEPTANCE VERDICT 2 (evidence missing, mismatched, stale or duplicated: nothing is decided).

Evidence is never trusted on its own say-so. Every input is recorded with its sha256 and the identity read from INSIDE it. Structural reports must carry the `evidence` block of exactly the documents given here
(a stale report, or one of another run, configuration, baseline or recording set, is rejected). Both score sets (raw and formatted, both sides) must cover exactly the expected recordings with no duplicates and
their predictions must equal the documents' own raw and final transcripts. The fixed rule compares AGGREGATE INTEGER errors and reference counts by cross-multiplication, never rounded percentages.

The fixed quality rule (unchanged): 1 all recordings complete; 2 raw WER and raw entity WER not higher than the baseline; 3 the same for the formatted transcripts; 4 no new large omission; 5 no new loop;
6 no `max_new_tokens` window and no unavailable or unexplained stop reason. Plus the structural gates and the plugin evidence (the controlled logits test and the live probes for stock and candidate).

Execution profiles (follow-up E): the candidate's settings id decides which execution is expected. A default-profile id runs in the default multiprocess mode (launcher record unset or "1", every document
observed `default` / `SyncMPClient`); a scheduling-profile id (an `execution` entry in its frozen table) must be observed `profile-in-process` / `InprocClient` with the variable "0". The plugin probes carry
an `execution_kind`: a default profile is probed in the DIAGNOSTIC in-process mode (and recorded as diagnostic only: it says nothing about the default multiprocess path), a scheduling profile in its own
production mode. The adapter's equivalence rests on the capture/replay report, bound to the capture, the verified package, the worker commit and the profile.

Baseline kinds. DEFAULT `matched-allocation` (everything above: the baseline ran in the candidate's allocation, on its GPU and commit). EXPLICIT `frozen-historical` (full development validation): the baseline is
the saved Transformers run, whose transcripts, plan and decode telemetry are carried by DOCUMENTS GENERATED BY THE STAGE 2 REPLAY (backend/settings/commit all `replay`: replay metadata is never evidence of a
GPU execution; the original generation is described by a declared `--baseline-source` file). Only the same-allocation identity requirements are waived (baseline settings id, clean commit, run-meta, same slurm
job and GPU, baseline parity reports, standalone references, the candidate standalone reference). Everything else is kept: model, audio, strategy and formatter equality, exact membership, window and
retry completeness against each side's persisted state, scores bound to the documents, the candidate's settings, fingerprint, frozen digest, commit, allocation and execution, the plugin and capture evidence,
and the six quality rules. Probes and capture made at another commit are accepted ONLY if the runtime tree (`meralion_worker/` and `configs/`) is identical in git at both commits. What this mode cannot
establish is listed under `not_established` in the output, never turned into a pass or a zero.
"""
