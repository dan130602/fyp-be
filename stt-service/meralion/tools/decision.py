class Evidence:
    def __init__(self):
        self.problems, self.inputs = [], []

    def problem(self, text):
        self.problems.append(text)

    def record(self, label, path, identity=None):
        path = Path(path)
        entry = {"label": label, "path": str(path), "sha256": hashlib.sha256(path.read_bytes()).hexdigest() if path.is_file() else None, "identity": identity or {}}
        if not path.exists():
            self.problem(f"{label}: {path} does not exist")
        self.inputs.append(entry)


def load(evidence, label, path):
    path = Path(path)
    if not path.is_file():
        evidence.record(label, path)
        return None
    data = acceptance.load_json(path)
    evidence.record(label, path)
    return data


def only(values, label, evidence, expected=None):
    if len(values) != 1:
        evidence.problem(f"{label}: expected exactly one value, found {list(values)}")
        return None
    value = list(values)[0]
    if expected is not None and value != expected:
        evidence.problem(f"{label}: expected {expected!r}, found {value!r}")
    return value


def pooled(rows, key):
    errors = sum((row.get(key) or {}).get("errors", 0) for row in rows.values())
    reference = sum((row.get(key) or {}).get("reference_words", 0) for row in rows.values())
    return errors, reference


def not_higher(candidate, baseline):
    """candidate (errors, reference) is not higher than baseline's: compared by cross-multiplication of integers; reference counts must match."""
    return candidate[0] * baseline[1] <= baseline[0] * candidate[1]


def read_scores(evidence, runs, run_id, label, expected_jobs, docs, field, historical=False, audio_docs=None):
    """The per-call score rows of a scored run, bound to the documents: exact recording set, no duplicates, predictions equal to the documents' own transcripts."""
    rows = {}
    path = Path(runs) / run_id / "scores" / "calls.jsonl"
    if not path.is_file():
        evidence.record(f"{label} scores", path)
        return None
    evidence.record(f"{label} scores", path, {"run_id": run_id})
    for line in path.read_text(encoding="utf-8").splitlines():
        row = json.loads(line)
        if row["call_id"] in rows:
            evidence.problem(f"{label}: duplicate score row for {row['call_id']}")
        rows[row["call_id"]] = row
    if sorted(rows) != sorted(expected_jobs):
        evidence.problem(f"{label}: the scored recordings differ from the expected {len(expected_jobs)}: missing {sorted(set(expected_jobs) - set(rows))[:3]}, unexpected {sorted(set(rows) - set(expected_jobs))[:3]}")
    predictions = Path(runs) / run_id / "raw" / "predictions"
    names = sorted(p.stem for p in predictions.glob("*.json")) if predictions.is_dir() else []
    if names != sorted(expected_jobs):
        evidence.problem(f"{label}: the imported predictions differ from the expected recordings")
    for name in sorted(set(names) & set(docs)):
        prediction = acceptance.load_json(predictions / f"{name}.json")
        block = docs[name]["meralion"]
        if prediction["transcript"] != block[field]:
            evidence.problem(f"{label}: the prediction for {name} is not this run's own {field}")
        settings = prediction.get("settings", {})
        audio_sha256 = ((audio_docs or docs).get(name) or docs[name])["meralion"]["audio"]["sha256"]                  # frozen-historical: the REAL audio hash is the candidate's (the replay documents carry a placeholder)
        if settings.get("audio_sha256") != audio_sha256 or (not historical and settings.get("config_fingerprint") != block["config_fingerprint"]):
            evidence.problem(f"{label}: the prediction for {name} carries another audio hash{'' if historical else ' or configuration fingerprint'} than the documents")
    return rows


SCHEDULING_VARIABLE = "VLLM_ENABLE_V1_MULTIPROCESSING"


def execution_expectation(settings_id, evidence):
    """The execution entry of the candidate's frozen table (None for a default profile); an unknown settings id is an evidence problem."""
    try:
        return frozen.execution_of(settings_id), True
    except DecodingSettingsError as error:
        evidence.problem(f"candidate settings id {settings_id!r} is not a known frozen settings id: {error}")
        return None, False


def execution_problem(expected, execution):
    """None when a document's recorded execution is the one the settings id requires, else why not."""
    if not isinstance(execution, dict):
        return "the document has no execution record"
    if expected is None:
        if execution.get("mode") != "default" or execution.get("engine_core_client") != "SyncMPClient" or execution.get("variable") not in (None, "1"):
            return f"a default profile must be observed default / SyncMPClient, found {execution}"
        return None
    if (execution.get("mode") != "profile-in-process" or execution.get("engine_core_client") != expected["engine_core_client"]
            or execution.get("variable") != expected[SCHEDULING_VARIABLE]):
        return f"a scheduling profile must be observed profile-in-process / {expected['engine_core_client']} with {SCHEDULING_VARIABLE}={expected[SCHEDULING_VARIABLE]!r}, found {execution}"
    return None


def engine_problem(settings_id, decoder_block):
    """None when a document's recorded effective engine is the one the settings id requires (the FP16 profile: dtype torch.float16, the frozen concurrency and attention backend), else why not.
    A profile without an expectation has none to check. A BF16 or lowered-concurrency run recorded under an FP16 settings id is an evidence problem, not a pass."""
    if frozen.effective_engine_expectation(settings_id) is None:
        return None
    observed = (decoder_block or {}).get("engine_effective")
    if not isinstance(observed, dict):
        return "the document has no engine_effective record (the settings id requires an observed engine)"
    differences = frozen.engine_differences(settings_id, observed)
    return "; ".join(differences) if differences else None


