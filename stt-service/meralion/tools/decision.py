REQUIRED_PLUGIN_CASES = (
    "bans_the_token_that_would_complete_a_repeated_6gram",
    "every_other_logit_is_unchanged",
    "is_argmax_invariant_is_false",
    "ngram_size_is_6",
    "no_ban_when_the_prefix_is_not_the_start_of_an_earlier_6gram",
    "no_ban_when_the_history_is_shorter_than_n",
    "placeholder_history_does_not_ban_the_real_token_15",
    "the_output_list_is_a_live_reference",
    "a_slot_swap_moves_the_history_with_it",
    "a_removed_slot_is_forgotten",
    "ngram_size_3_from_the_environment_bans_7",
    "the_default_ngram_size_is_6_when_unset",
)
PLUGIN_TOOL_PATH = "stt-service/meralion/tools/origami/plugin_logits_test.py"


def committed_blob_sha256(repo, commit, path):
    """(sha256 of the BYTES of `path` in the git tree of `commit`, None), or (None, why it cannot be established). Bytes straight from the blob: no text conversion, no working-tree file."""
    import subprocess
    try:
        done = subprocess.run(["git", "-C", str(repo), "cat-file", "blob", f"{commit}:{path}"], capture_output=True)
    except OSError as error:
        return None, f"git could not be run ({error})"
    if done.returncode != 0:
        return None, f"{path} cannot be read at commit {commit!r} ({done.stderr.decode('utf-8', 'replace').strip()[:100]})"
    return hashlib.sha256(done.stdout).hexdigest(), None


def plugin_gate(plugin):
    """The structural value: True only when the report holds EVERY required case and each is True. Computed from the case values, never from the report's own `passed` flag."""
    cases = plugin.get("cases") if isinstance(plugin, dict) else None
    return isinstance(cases, dict) and all(cases.get(name) is True for name in REQUIRED_PLUGIN_CASES)


def plugin_report_problems(plugin):
    """Why a controlled-logits-test report is malformed, incomplete or self-contradictory (evidence problems: NOT AN ACCEPTANCE VERDICT). A case that is `False` is NOT a problem here:
    complete, consistent evidence of a genuinely failed case is valid evidence and the candidate is REJECTED through plugin_gate."""
    problems = []
    if plugin.get("test") != "plugin_logits_test":
        problems.append(f"the report is not a plugin_logits_test report (test {plugin.get('test')!r})")
    cases = plugin.get("cases")
    if not isinstance(cases, dict):
        return problems + ["the report has no cases object"]
    missing = [name for name in REQUIRED_PLUGIN_CASES if name not in cases]
    extra = sorted(set(cases) - set(REQUIRED_PLUGIN_CASES))
    if missing:
        problems.append(f"required cases are missing from the report: {missing}")
    if extra:
        problems.append(f"the report carries cases that are not required: {extra}")
    untested = sorted(name for name, value in cases.items() if value is None)
    malformed = sorted(name for name, value in cases.items() if value is not None and not isinstance(value, bool))
    if untested:
        problems.append(f"cases that were not tested (reported None): {untested} (in the vLLM environment every case must run)")
    if malformed:
        problems.append(f"cases with a value that is neither true nor false: {malformed}")
    if plugin.get("not_testable_here"):
        problems.append(f"cases that could not be run: {plugin.get('not_testable_here')} (in the vLLM environment every case must run)")
    if not missing and not extra and not malformed:
        failed = sorted(name for name, value in cases.items() if value is False)
        if sorted(plugin.get("failed") or []) != failed or not isinstance(plugin.get("failed"), list):
            problems.append(f"the summary's failed list {plugin.get('failed')!r} is not the cases that are false {failed}")
        if sorted(plugin.get("not_testable_here") or []) != sorted(untested):
            problems.append(f"the summary's not_testable_here {plugin.get('not_testable_here')!r} is not the cases reported None {untested}")
        if plugin.get("passed") is not (not failed and not untested):
            problems.append(f"the summary's passed flag {plugin.get('passed')!r} contradicts the cases (false cases {failed}, untested {untested})")
    return problems


def tool_hash_problems(block, repo, resolver=None):
    """The report's tool_sha256 must be the sha256 of the test file AS COMMITTED at the report's own worker commit (the commit that bind_commit ties to the runs). Cannot establish = problem."""
    commit = block.get("worker_git_commit")
    found = block.get("tool_sha256")
    if not commit:
        return ["the report names no worker commit, so its tool hash cannot be compared with the committed test file"]
    expected, why = (resolver or committed_blob_sha256)(repo, commit, PLUGIN_TOOL_PATH)
    if expected is None:
        return [f"the test file's committed hash cannot be established: {why}"]
    if found != expected:
        return [f"tool_sha256 is {found!r} in the report, the committed {PLUGIN_TOOL_PATH} at {commit} has {expected!r} (the test that ran is not the committed one)"]
    return []


def plugin_problems(plugin, package_manifest, candidate_docs, repo=None, resolver=None):
    """Why a controlled-logits-test report is not evidence about THIS run's package and runtime (an empty list when it is). The commit is bound separately with bind_commit."""
    problems = plugin_report_problems(plugin)
    block = plugin.get("evidence")
    if not isinstance(block, dict):
        return problems + ["the report has no evidence block (it predates the bound form)"]
    problems += tool_hash_problems(block, repo if repo is not None else ROOT.parents[1], resolver)
    if block.get("uuid_device_visible") is not False:
        problems.append(f"it was made where a device UUID was visible (uuid_device_visible {block.get('uuid_device_visible')!r}, CUDA_VISIBLE_DEVICES {block.get('cuda_visible_devices')!r})")
    files = (block.get("package") or {}).get("files_sha256") or {}
    expected_files = (package_manifest or {}).get("files") or {}
    for name in PLUGIN_FILES:
        if not expected_files.get(name):
            problems.append(f"the package manifest has no hash for {name}")
        elif files.get(name) != expected_files[name]:
            problems.append(f"{name} has sha256 {files.get(name)!r} in the report, the verified package's is {expected_files[name]!r}")
    versions = block.get("versions") or {}
    seen = {key: set() for key in PLUGIN_VERSIONS}
    for document in candidate_docs.values():
        packages = ((document["meralion"]["decoder"].get("runtime") or {}).get("packages")) or {}
        for key in PLUGIN_VERSIONS:
            seen[key].add(packages.get(key))
    for key in PLUGIN_VERSIONS:
        if seen[key] != {versions.get(key)}:
            problems.append(f"{key} is {versions.get(key)!r} in the report but {sorted(map(str, seen[key]))} in the evaluated documents")
    return problems


def probe_problem(expected, probe):
    """None when a plugin probe was made in the execution kind its settings id requires, else why not."""
    execution = probe.get("execution")
    if expected is None:
        if probe.get("execution_kind") != "diagnostic-in-process" or probe.get("diagnostic_only") is not True:
            return f"a default-profile probe must be a diagnostic in-process probe (execution_kind {probe.get('execution_kind')!r}, diagnostic_only {probe.get('diagnostic_only')!r})"
        return None
    if probe.get("execution_kind") != "profile-in-process" or probe.get("diagnostic_only") is not False or not isinstance(execution, dict) \
            or execution.get("engine_core_client") != expected["engine_core_client"]:
        return f"a scheduling-profile probe must be profile-in-process / {expected['engine_core_client']} and not diagnostic (found {probe.get('execution_kind')!r}, {execution})"
    return None


def runtime_tree_problem(repo, commit_a, commit_b):
    """None when the runtime trees of the two commits are identical in git, else why not (a commit that cannot be resolved is a problem too)."""
    import subprocess
    for path in RUNTIME_TREES:
        found = []
        for commit in (commit_a, commit_b):
            done = subprocess.run(["git", "-C", str(repo), "rev-parse", f"{commit}:{path}"], capture_output=True, text=True)
            if done.returncode != 0:
                return f"{path} cannot be resolved at commit {commit!r} ({done.stderr.strip()[:80]})"
            found.append(done.stdout.strip())
        if found[0] != found[1]:
            return f"{path} differs between {commit_a} and {commit_b}"
    return None


def bind_commit(evidence, structural, informational, label, found, run_commit, historical, repo):
    """The commit an artefact was made at must be the runs' commit. In frozen-historical mode an earlier commit is accepted only with an identical runtime tree (recorded as its own structural item)."""
    if found == run_commit:
        return
    if not historical:
        evidence.problem(f"{label}: made with worker commit {found!r}, the runs used {run_commit!r}")
        return
    problem = runtime_tree_problem(repo, found, run_commit)
    key = f"runtime_tree_unchanged_since_{label.replace(' ', '_')}"
    if problem:
        evidence.problem(f"{label}: made with worker commit {found!r}, the runs used {run_commit!r}, and the runtime tree is not shown to be identical: {problem}")
    else:
        structural[key] = True
        informational[key] = f"made at {found}; meralion_worker/ and configs/ are identical in git at the runs' commit {run_commit}"


def check_baseline_source(evidence, source, replay_report, replay_path, baseline_evidence, expected_calls, scores):
    """The declared source of a frozen-historical baseline, bound to the documents and the replay report given here."""
    if source is None:
        return
    if source.get("schema") != SOURCE_SCHEMA:
        evidence.problem(f"baseline source: not a {SOURCE_SCHEMA} document")
    generation = source.get("original_generation") or {}
    for key in ("scored_runs", "hardware", "hardware_evidence", "runner"):
        if not generation.get(key):
            evidence.problem(f"baseline source: original_generation.{key} is not declared")
    if generation.get("replay_documents_are_gpu_evidence") is not False:
        evidence.problem("baseline source: it must state replay_documents_are_gpu_evidence false (replay metadata is not evidence of a GPU execution)")
    if generation.get("scored_runs") != {"raw": scores.get("baseline_raw"), "final": scores.get("baseline_final")}:
        evidence.problem(f"baseline source: it declares scored runs {generation.get('scored_runs')}, the scores given are {scores.get('baseline_raw')!r} and {scores.get('baseline_final')!r}")
    replay = source.get("replay") or {}
    if replay.get("documents_sha256") != baseline_evidence.get("documents_sha256"):
        evidence.problem("baseline source: its replay documents hash is not that of the baseline documents given here")
    if replay_report is None:
        return
    if replay.get("report_sha256") != hashlib.sha256(Path(replay_path).read_bytes()).hexdigest():
        evidence.problem("baseline source: its replay report hash is not that of the replay report given here")
    reference = replay_report.get("reference") or {}
    if not (replay_report.get("passed") is True and (replay_report.get("expected") or {}).get("calls") == expected_calls and reference.get("raw_equal") == expected_calls
            and reference.get("results_transcripts_equal_target") == expected_calls and reference.get("mismatches") == []):
        evidence.problem("baseline replay report: it does not show the replay reproducing the frozen raw and formatted transcripts for every expected recording")
    if replay_report.get("config_fingerprint") not in baseline_evidence.get("config_fingerprints", []):
        evidence.problem("baseline replay report: its configuration fingerprint is not that of the baseline documents")


def decide(args):
    evidence, items = Evidence(), {}
    historical = getattr(args, "baseline_kind", MATCHED) == HISTORICAL
    repo = getattr(args, "repo", None) or ROOT.parents[1]
    not_established = []
    expected = acceptance.read_jobs(args.jobs)
    evidence.record("job manifest", args.jobs, {"recordings": len(expected)})
    docs, states, evid = {}, {}, {}
    sides = ("candidate", "baseline") if historical else ("candidate", "baseline", "candidate_c4", "baseline_c4")
    for side in ("candidate_c4", "baseline_c4"):
        docs[side], evid[side] = {}, {}
    for side in sides:
        folder = getattr(args, f"{side}_docs", None)
        if folder is None:
            evidence.problem(f"{side}: no documents folder was given")
            docs[side], evid[side] = {}, {}
            continue
        loaded, doc_problems = acceptance.scan_documents(folder)
        docs[side] = loaded
        for problem in doc_problems:
            evidence.problem(f"{side}: {problem}")
        evid[side] = acceptance.evidence_of(loaded) if loaded else {}
        evidence.record(f"{side} documents", folder, {"documents_sha256": evid[side].get("documents_sha256"), "recordings": len(loaded)})
    # ---- identity of the two sides ----
    candidate_config = cfg.load_runtime_config(args.candidate_config, env={})
    c, b = evid["candidate"], evid["baseline"]
    if c and b:
        only(c["settings_ids"], "candidate settings id", evidence, expected=args.candidate_settings)
        only(c["config_fingerprints"], "candidate config fingerprint", evidence, expected=candidate_config.fingerprint)
        only(c["backends"], "candidate backend", evidence, expected="vllm")
        only(b["settings_ids"], "baseline settings id", evidence, expected=HISTORICAL_BACKEND if historical else BASELINE_SETTINGS)
        only(b["backends"], "baseline backend", evidence, expected=HISTORICAL_BACKEND if historical else "transformers")
        for label, ev in (("candidate", c), ("baseline", b)):
            only(ev["strategy_ids"], f"{label} strategy", evidence, expected=STRATEGY_V2)
        if c["formatters"] != b["formatters"]:
            evidence.problem(f"the candidate and baseline formatters differ: {c['formatters']} against {b['formatters']}")
        if c["model_manifest_sha256"] != b["model_manifest_sha256"]:
            evidence.problem("the candidate and baseline used different model manifests")
        if not historical and c["audio_sha256"] != b["audio_sha256"]:
            evidence.problem("the candidate and baseline were decoded from different audio files")
        if historical:
            commits = set(c["worker_commits"])
            only(b["worker_commits"], "baseline worker commit (replay documents)", evidence, expected=HISTORICAL_BACKEND)
        else:
            commits = set(c["worker_commits"]) | set(b["worker_commits"])
        if len(commits) != 1 or next(iter(commits)) in ("unknown", "None") or next(iter(commits)).endswith("-dirty"):
            evidence.problem(f"the worker commit must be one clean recorded commit in {'the candidate' if historical else 'both'} run{'' if historical else 's'}, found {sorted(commits)}")
    for side in (() if historical else ("candidate_c4", "baseline_c4")):
        parent = "candidate" if side == "candidate_c4" else "baseline"
        e = evid[side]
        if e and evid[parent]:
            if e["settings_ids"] != evid[parent]["settings_ids"] or e["config_fingerprints"] != evid[parent]["config_fingerprints"] or e["worker_commits"] != evid[parent]["worker_commits"]:
                evidence.problem(f"{side}: not the same settings, configuration and commit as the {parent} pilot run")
            if len(e["jobs"]) != 1:
                evidence.problem(f"{side}: a standalone reference must hold exactly one recording")
    # ---- run metadata: same allocation, same physical GPU, normal multiprocess mode ----
    metas = {}
    for side in (("candidate",) if historical else ("candidate", "baseline")):
        folder = getattr(args, f"{side}_docs", None)
        meta = load(evidence, f"{side} run-meta", Path(folder).parent.parent / "run-meta.json") if folder is not None else None
        metas[side] = meta or {}
    expected_execution, settings_known = execution_expectation(args.candidate_settings, evidence)
    allocation = None
    if historical and metas.get("candidate"):
        meta = metas["candidate"]
        for key in ("slurm_job_id", "gpu_uuid", "worker_git_commit"):
            if not meta.get(key):
                evidence.problem(f"candidate run-meta records no {key}")
        if c and meta.get("worker_git_commit") not in c.get("worker_commits", []):
            evidence.problem(f"candidate run-meta records commit {meta.get('worker_git_commit')!r}, the documents {c.get('worker_commits')}")
        allocation = {"slurm_job_id": meta.get("slurm_job_id"), "gpu_uuid": meta.get("gpu_uuid"), "pip_freeze_sha256": meta.get("pip_freeze_sha256"), "host": meta.get("host")}
    if historical and c:
        digests = sorted({d["meralion"]["decoder"].get("frozen_digest") for d in docs["candidate"].values()})
        if settings_known and digests != [frozen.frozen_digest(args.candidate_settings)]:
            evidence.problem(f"candidate settings digest {digests} is not the frozen table's {frozen.frozen_digest(args.candidate_settings)!r}")
    for side, meta in metas.items():                                  # an acceptance run is ONE uninterrupted attempt (REV 3.0 A2): a restart or a second attempt is an evidence problem
        folder = getattr(args, f"{side}_docs", None)
        if meta and meta.get("restart_count") not in (None, 0):
            evidence.problem(f"{side}: the run was restarted by the scheduler (restart_count {meta.get('restart_count')!r}); an interrupted run is not acceptance evidence")
        if meta and meta.get("attempt") not in (None, 1):
            evidence.problem(f"{side}: run-meta records attempt {meta.get('attempt')!r}; only a first and only attempt is acceptance evidence")
        if folder is not None and (Path(folder).parent.parent / "attempts").exists():
            evidence.problem(f"{side}: an attempts/ folder exists next to the run; a resumed run is never acceptance evidence")
    if all(metas.values()):
        if not historical:
            for key in ("slurm_job_id", "gpu_uuid"):
                if not metas["candidate"].get(key) or metas["candidate"].get(key) != metas["baseline"].get(key):
                    evidence.problem(f"the candidate and baseline were not run on the same {key}: {metas['candidate'].get(key)} against {metas['baseline'].get(key)}")
        allowed = {"baseline": (None, "unset", "1"), "candidate": (None, "unset", "1") if expected_execution is None else (None, "unset", expected_execution[SCHEDULING_VARIABLE])}
        for side in metas:
            if metas[side].get("vllm_enable_v1_multiprocessing") not in allowed[side]:
                evidence.problem(f"{side}: the launcher recorded {SCHEDULING_VARIABLE}={metas[side].get('vllm_enable_v1_multiprocessing')!r}, which its execution profile does not allow "
                                 f"(an acceptance run never sets it from the launcher; a scheduling profile sets it itself)")
    if settings_known:
        for side in (("candidate",) if historical else ("candidate", "candidate_c4")):
            seen = {execution_problem(expected_execution, document["meralion"]["decoder"].get("execution")) for document in docs[side].values()}
            seen |= {engine_problem(args.candidate_settings, document["meralion"]["decoder"]) for document in docs[side].values()}
            for problem in sorted(p for p in seen if p):
                evidence.problem(f"{side}: {problem}")
    # ---- structural: membership and first-pass completeness, recomputed here, and persisted plans ----
    for side in ("candidate", "baseline"):
        for problem in acceptance.check_membership(expected, docs[side]):
            evidence.problem(f"{side}: {problem}")
    structural = {}
    for side in ("candidate", "baseline"):
        found = [p for d in docs[side].values() for p in acceptance.check_window_coverage(d)]
        ids = acceptance.invocation_ids(docs[side]) if docs[side] else []
        try:
            state = acceptance.load_state(getattr(args, f"{side}_state"), ids[0]) if len(ids) == 1 else None
        except FileNotFoundError:
            state = None
        if state is None:
            evidence.problem(f"{side}: the persisted state cannot be read")
        else:
            found += acceptance.check_persisted_plan(docs[side], state) + acceptance.check_recomputed_plan(docs[side], state)
            states[side] = state
        structural[f"{side}_windows_plan_and_state_recomputed_ok"] = not found
    # ---- structural reports must be bound to exactly these documents ----
    parity_inputs = [("candidate parity report", args.candidate_parity, "candidate")]
    if not historical:
        parity_inputs += [("baseline parity report", args.baseline_parity, "baseline"), ("candidate standalone parity report", args.candidate_c4_parity, "candidate_c4"),
                          ("baseline standalone parity report", args.baseline_c4_parity, "baseline_c4")]
    for label, path, side in parity_inputs:
        if path is None:
            evidence.problem(f"{label}: no report was given")
            continue
        report = load(evidence, label, path)
        if report is None:
            continue
        if report.get("evidence") != evid[side]:
            evidence.problem(f"{label}: its evidence block is not that of the {side} documents given here (stale, or a report of another run)")
        if report.get("verdict") != "ACCEPTED":
            structural[label.replace(" ", "_") + "_is_ACCEPTED"] = False
    compare = load(evidence, "backend comparison report", args.compare)
    if compare is not None:
        if compare.get("evidence") != {"tf": evid["baseline"], "vllm": evid["candidate"]}:
            evidence.problem("backend comparison report: not bound to the baseline and candidate documents given here (stale, or another run)")
        bad = [name for name, ok in compare.get("gates", {}).items() if name.startswith(("tf_", "vllm_")) and not ok]
        structural["comparison_structural_gates"] = not bad and compare.get("gates", {}).get("all_calls_in_both", False)
    # ---- plugin evidence ----
    plugin = load(evidence, "controlled logits test", args.plugin_test)
    if plugin is not None:
        structural["plugin_controlled_logits_test_passed"] = plugin_gate(plugin)                      # from the case values (REV 4.1 A1), not from the report's own flag
    commit = next(iter(set(c.get("worker_commits", [])))) if c else None
    informational = {}
    for label, path, settings in (("stock plugin probe", args.probe_stock, "stock-vllm-package-v1"), ("candidate plugin probe", args.probe_candidate, args.candidate_settings)):
        probe = load(evidence, label, path)
        if probe is None:
            continue
        if probe.get("settings_id") != settings:
            evidence.problem(f"{label}: made for settings {probe.get('settings_id')!r}, expected {settings!r}")
        bind_commit(evidence, structural, informational, label, probe.get("worker_git_commit"), commit, historical, repo)
        probe_expected, probe_known = execution_expectation(settings, evidence)
        if probe_known:
            problem = probe_problem(probe_expected, probe)
            if problem:
                evidence.problem(f"{label}: {problem}")
            elif probe.get("diagnostic_only"):
                informational[label.replace(" ", "_") + "_is_diagnostic_only"] = "made in the diagnostic in-process mode: evidence about the plugin inside the engine, not about the default multiprocess execution"
        structural[label.replace(" ", "_") + "_passed"] = bool(probe.get("passed"))
    # ---- the adapter's equivalence: live capture + CPU replay, bound to the capture, the verified package, the commit and the profile ----
    capture_doc = load(evidence, "live capture", args.capture)
    replay = load(evidence, "capture replay report", args.capture_replay)
    package_manifest = load(evidence, "package manifest", args.package_manifest)
    if plugin is not None:                                            # the controlled test is evidence only for the commit, package files and versions it names, made where no device UUID was visible
        bind_commit(evidence, structural, informational, "controlled logits test", (plugin.get("evidence") or {}).get("worker_git_commit"), commit, historical, repo)
        if package_manifest is None:
            evidence.problem("controlled logits test: it cannot be bound to the verified package without the package manifest")
        for problem in plugin_problems(plugin, package_manifest or {}, docs["candidate"], repo=repo, resolver=getattr(args, "blob_resolver", None)):
            evidence.problem(f"controlled logits test: {problem}")
    if capture_doc is not None and replay is not None and package_manifest is not None:
        bound = replay.get("evidence") or {}
        capture_commit = capture_doc.get("worker_git_commit")
        if historical and capture_commit != commit:
            bind_commit(evidence, structural, informational, "live capture", capture_commit, commit, historical, repo)
        expected_bound = {"capture_sha256": hashlib.sha256(Path(args.capture).read_bytes()).hexdigest(), "settings_id": args.candidate_settings, "worker_commit": capture_commit if historical else commit,
                          "wheel_sha256": (package_manifest.get("artifact") or {}).get("sha256"), "package_manifest_sha256": hashlib.sha256(Path(args.package_manifest).read_bytes()).hexdigest()}
        for key, want in expected_bound.items():
            if bound.get(key) != want:
                evidence.problem(f"capture replay report: its {key} is {bound.get(key)!r}, expected {want!r} (a report of another capture, package, commit or profile)")
        for key, want in (("settings_id", args.candidate_settings),) + (() if historical else (("worker_git_commit", commit),)):
            if capture_doc.get(key) != want:
                evidence.problem(f"live capture: its {key} is {capture_doc.get(key)!r}, expected {want!r}")
        checks = replay.get("checks")
        structural["adapter_equivalent_by_capture_replay"] = bool(replay.get("passed")) and isinstance(checks, dict) and bool(checks) and all(checks.values())
    # ---- scores, bound to the documents ----
    runs = {}
    for key, side, field in (("candidate_raw", "candidate", "transcript_raw"), ("candidate_final", "candidate", "transcript_final"), ("baseline_raw", "baseline", "transcript_raw"), ("baseline_final", "baseline", "transcript_final")):
        runs[key] = read_scores(evidence, args.runs, args.score[key], key.replace("_", " "), expected, docs[side], field, historical=historical and side == "baseline", audio_docs=docs["candidate"] if historical and side == "baseline" else None)
    # ---- frozen-historical: the declared source of the baseline, and what it cannot establish ----
    source_sha256, baseline_note = None, None
    if historical:
        source_path, replay_path = getattr(args, "baseline_source", None), getattr(args, "baseline_replay_report", None)
        if source_path is None or replay_path is None:
            evidence.problem("frozen-historical needs --baseline-source and --baseline-replay-report")
        else:
            source = load(evidence, "baseline source", source_path)
            replay_report = load(evidence, "baseline replay report", replay_path)
            source_sha256 = hashlib.sha256(Path(source_path).read_bytes()).hexdigest() if Path(source_path).is_file() else None
            check_baseline_source(evidence, source, replay_report, replay_path, b, len(expected), args.score)
            generation = (source or {}).get("original_generation") or {}
            baseline_note = {"kind": HISTORICAL, "source_sha256": source_sha256, "original_generation": generation, "documents": "generated by the Stage 2 replay from saved decodes (backend replay): not GPU execution evidence"}
            rows = compare_backends.all_decodes(docs["baseline"]) if docs.get("baseline") else []
            unavailable = {kind: sum(1 for k, _, _, result in rows if k == kind and result.get("stop_reason") is None) for kind in ("window", "retry")}
            total = {kind: sum(1 for k, _, _, _ in rows if k == kind) for kind in ("window", "retry")}
            not_established += [
                f"same-hardware comparison: the baseline was generated on {generation.get('hardware')!r} ({generation.get('hardware_evidence')}); the candidate ran on GPU {(allocation or {}).get('gpu_uuid')}; "
                "this compares complete configurations across hardware and cannot isolate the backend",
                "baseline worker commit and run record: the original run predates the worker; its documents are replay-generated",
                f"baseline stop reasons: unavailable for {unavailable['window']} of {total['window']} first-pass decodes and {unavailable['retry']} of {total['retry']} retry decodes (kept unavailable, never counted as end_token)",
                "baseline audio identity: the replay documents carry placeholder audio hashes; the audio is bound through the hashes the frozen scored runs recorded, compared with the candidate's real audio hashes",
                "baseline prediction fingerprint binding: the frozen predictions carry no worker configuration fingerprint (bound by audio hash and exact transcripts instead)",
                "standalone single-recording reference: not part of this validation (no candidate or baseline standalone run)"]
    # ---- the fixed quality rule, from integer counts ----
    quality = {}
    if all(runs.values()):
        quality["1_all_recordings_complete"] = all(len(docs[s]) == len(expected) for s in ("candidate", "baseline")) and all(len(r) == len(expected) for r in runs.values())
        table = {}
        for kind in ("raw", "final"):
            cand_rows, base_rows = runs[f"candidate_{kind}"], runs[f"baseline_{kind}"]
            for metric, key in (("wer", "wer"), ("entity_wer", "entity_wer")):
                cand, base = pooled(cand_rows, key), pooled(base_rows, key)
                if cand[1] != base[1]:
                    evidence.problem(f"{kind} {metric}: reference counts differ between candidate and baseline ({cand[1]} against {base[1]}): not the same references")
                table[f"{kind}_{metric}"] = {"candidate_errors": cand[0], "baseline_errors": base[0], "reference_tokens": cand[1], "candidate_not_higher": not_higher(cand, base)}
        quality["2_raw_wer_and_entity_wer_not_higher"] = table["raw_wer"]["candidate_not_higher"] and table["raw_entity_wer"]["candidate_not_higher"]
        quality["3_formatted_wer_and_entity_wer_not_higher"] = table["final_wer"]["candidate_not_higher"] and table["final_entity_wer"]["candidate_not_higher"]
        new_events = {}
        for kind, path in (("raw", args.config_compare_raw), ("final", args.config_compare_final)):
            data = load(evidence, f"config_compare {kind}", path)
            if data is None:
                continue
            candidate_run, baseline_run = args.score[f"candidate_{kind}"], args.score[f"baseline_{kind}"]
            if data.get("base") != baseline_run and (data.get("base") or {}).get("run_id") != baseline_run and baseline_run not in json.dumps(data.get("base")):
                evidence.problem(f"config_compare {kind}: its baseline is not {baseline_run}")
            if candidate_run not in data.get("candidates", {}):
                evidence.problem(f"config_compare {kind}: it does not contain the candidate run {candidate_run}")
            else:
                new_events[kind] = len(data["candidates"][candidate_run]["large_omission_events"]["new"])
        quality["4_no_new_large_omission_raw_and_formatted"] = bool(new_events) and len(new_events) == 2 and all(n == 0 for n in new_events.values())
        quality_details = {"integer_counts": table, "new_large_omissions": new_events}
    else:
        quality_details = {}
    if states.keys() == {"candidate", "baseline"}:
        recomputed = compare_backends.compare(docs["baseline"], docs["candidate"], expected_jobs=expected, tf_state=args.baseline_state, vllm_state=args.candidate_state)
        quality["5_no_new_loops"] = not recomputed["loops"]["new_in_vllm"]
        counts = recomputed["stop_reasons"]["vllm"]["counts"]
        quality["6_no_max_new_tokens_no_unavailable_or_unexplained_stop"] = counts.get("max_new_tokens", 0) == 0 and counts.get("None", 0) == 0 and counts.get("other", 0) == 0
        quality_details["candidate_stop_reasons"] = counts
        quality_details["new_loops"] = len(recomputed["loops"]["new_in_vllm"])
    # ---- per-language report (reported, not gating) ----
    languages = {}
    if all(runs.values()) and not evidence.problems:
        languages_file = getattr(args, "languages", None)
        pilot = acceptance.load_json(languages_file) if languages_file else {call: {"language": info["language"]} for call, info in acceptance.load_json(args.pilot)["per_call"].items()}
        if languages_file:
            evidence.record("language map", languages_file)
        unknown = sorted(set(expected) - set(pilot))
        if unknown:
            evidence.problem(f"no language is known for {len(unknown)} expected recordings: {unknown[:5]}")
            pilot = {**pilot, **{call: {"language": "UNKNOWN"} for call in unknown}}
        for kind in ("raw", "final"):
            for call in expected:
                language = pilot[call]["language"]
                for side in ("candidate", "baseline"):
                    for metric in ("wer", "entity_wer"):
                        cell = languages.setdefault(language, {}).setdefault(f"{kind}_{metric}", {"candidate": [0, 0], "baseline": [0, 0]})[side]
                        row = (runs[f"{side}_{kind}"][call].get(metric) or {})
                        cell[0] += row.get("errors", 0)
                        cell[1] += row.get("reference_words", 0)
        for language, metrics in languages.items():
            for name, cell in metrics.items():
                cell["candidate_higher"] = not not_higher(tuple(cell["candidate"]), tuple(cell["baseline"]))
    # ---- verdict ----
    all_items = {**{f"structural:{k}": v for k, v in structural.items()}, **{f"quality:{k}": v for k, v in quality.items()}}
    required_quality = {"1_all_recordings_complete", "2_raw_wer_and_entity_wer_not_higher", "3_formatted_wer_and_entity_wer_not_higher", "4_no_new_large_omission_raw_and_formatted", "5_no_new_loops",
                        "6_no_max_new_tokens_no_unavailable_or_unexplained_stop"}
    missing_items = sorted(required_quality - set(quality))
    if missing_items:
        evidence.problem(f"quality items could not be evaluated: {missing_items}")
    if evidence.problems:
        verdict, code = "NOT AN ACCEPTANCE VERDICT", 2
    elif all(all_items.values()):
        verdict, code = "ACCEPTED", 0
    else:
        verdict, code = "REJECTED", 1
    return {"verdict": verdict, "exit_code": code, "evidence_problems": evidence.problems, "failed_items": sorted(k for k, v in all_items.items() if not v), "items": all_items,
            "quality_details": quality_details, "per_language": languages, "candidate_settings": args.candidate_settings, "inputs": evidence.inputs,
            "identity": {"candidate": evid["candidate"], "baseline": evid["baseline"], "baseline_kind": HISTORICAL if historical else MATCHED, "baseline_source_sha256": source_sha256,
                         "candidate_allocation": allocation,
                         "candidate_frozen_digests": sorted({d["meralion"]["decoder"].get("frozen_digest") for d in docs["candidate"].values()}) if docs.get("candidate") else []},
            "baseline": baseline_note or {"kind": MATCHED}, "not_established": not_established, "informational": informational,
            "note": "per-language regressions are reported, not gating; WER is compared on aggregate integer errors and reference counts"}


MATCHED_ONLY_ARGUMENTS = ("candidate-c4-parity", "baseline-parity", "baseline-c4-parity", "candidate-c4-docs", "baseline-c4-docs")


def build_parser():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    for name in ("jobs", "pilot", "runs", "candidate-config", "out", "compare", "plugin-test", "probe-stock", "probe-candidate", "config-compare-raw", "config-compare-final",
                 "candidate-parity", "candidate-docs", "candidate-state", "baseline-docs", "baseline-state", "capture", "capture-replay", "package-manifest"):
        parser.add_argument(f"--{name}", type=Path, required=True)
    for name in MATCHED_ONLY_ARGUMENTS:                                     # required in the default mode only
        parser.add_argument(f"--{name}", type=Path)
    parser.add_argument("--baseline-kind", choices=(MATCHED, HISTORICAL), default=MATCHED)
    for name in ("baseline-source", "baseline-replay-report", "languages", "repo"):
        parser.add_argument(f"--{name}", type=Path)
    parser.add_argument("--candidate-settings", default=CANDIDATE_SETTINGS)
    parser.add_argument("--score", nargs=4, metavar="KEY=RUN", required=True)
    return parser


def main(argv=None):
    parser = build_parser()
    args = parser.parse_args(argv)
    if args.baseline_kind == MATCHED:
        missing = [f"--{name}" for name in MATCHED_ONLY_ARGUMENTS if getattr(args, name.replace("-", "_")) is None]
        if missing:
            parser.error(f"the matched-allocation mode needs {', '.join(missing)}")
    elif args.baseline_source is None or args.baseline_replay_report is None:
        parser.error("--baseline-kind frozen-historical needs --baseline-source and --baseline-replay-report")
    scores = dict(item.split("=", 1) for item in args.score)
    if set(scores) != {"candidate_raw", "candidate_final", "baseline_raw", "baseline_final"}:
        print("decision: --score needs candidate_raw=, candidate_final=, baseline_raw= and baseline_final=", file=sys.stderr)
        return 2
    args.score = scores
    result = decide(args)
    if args.out.exists():
        raise SystemExit(f"decision file already exists, not overwriting it: {args.out}")
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(result, indent=1, ensure_ascii=False, sort_keys=True) + "\n", encoding="utf-8")
    print(json.dumps({"verdict": result["verdict"], "failed_items": result["failed_items"], "evidence_problems": result["evidence_problems"][:6]}, indent=1, ensure_ascii=False))
    return result["exit_code"]


if __name__ == "__main__":
    sys.exit(main())
