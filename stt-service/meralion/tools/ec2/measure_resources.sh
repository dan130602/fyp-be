#!/bin/bash
# Measure ONE run of a workload in ONE fresh container with the DECLARED limits (REV 3.0 B5, REV 3.2 Amendment 8, REV 3.3 Amendment 9, REV 3.4). Run on the EC2 test host as the Docker user; the verdict is
# computed by resource_summary.py from what this script collects. Nothing here changes a setting of the worker.
#
#   bash measure_resources.sh <run name> <out dir> <ec2-declaration.json> <primary|downsize> <image> -- <workload command...>
#   DOCKER_EXTRA_ARGS="--gpus all -v /data/model:/model:ro -v /data/cache-cold:/cache -e FLASHINFER_WORKSPACE_BASE=/cache/flashinfer ..." (volumes, caches, GPU access: word-split on purpose)
#
# HOLD-AND-EXEC: the container's main process only waits (`sleep infinity`); the workload runs through `docker exec`. That lets the cgroup outlive a NORMAL workload exit, nothing more: the holder is in the same
# cgroup under the same memory limit, so an OOM kill, a container stop or a daemon fault can still remove it. Nothing is assumed:
#   * the holder and the cgroup are checked before the workload and again before the final read; their death is recorded;
#   * the exec CLIENT returning or timing out is NOT taken to mean that the workload stopped: its pid is recorded in the container, and before any metric is called final the workload is confirmed
#     terminated (terminated with SIGTERM, then SIGKILL after the declared grace period, if it was still running) and cgroup.procs holds only the holder;
#   * the final memory.peak / memory.events / memory.pressure / memory.swap.events and `docker inspect` are read while the container is still ALIVE, on success and on every failure path (a trap covers an
#     interrupt of this script too), and only THEN is the container removed; a read that cannot be made is written as finality=last_sampled or unavailable WITH the reason, never skipped silently.
# Overrides for tests: DOCKER, CGROUP_BASE, FREE_CMD, PYTHON, SUMMARY_PY.
set -uo pipefail
NAME=${1:?run name}; OUT=${2:?output folder}; DECL=${3:?declaration file}; LIMITKEY=${4:?primary|downsize}; IMAGE=${5:?image}
shift 5
[ "${1:-}" = "--" ] && shift
[ "$#" -ge 1 ] || { echo "no workload command given"; exit 2; }
WORKLOAD=("$@")
DOCKER=${DOCKER:-docker}
CGROUP_BASE=${CGROUP_BASE:-/sys/fs/cgroup}
FREE_CMD=${FREE_CMD:-free -m}
PYTHON=${PYTHON:-python3}
SUMMARY_PY=${SUMMARY_PY:-$(dirname "$0")/resource_summary.py}

# the declared values (generated by our own tool: KEY=VALUE lines of numbers and safe strings)
while IFS='=' read -r key value; do
  key=${key%$'\r'}; value=${value%$'\r'}                      # a Python that writes CRLF (Windows) must not leak a carriage return into a number
  [ -n "$key" ] && declare "$key=$value"
done < <("$PYTHON" "$SUMMARY_PY" declaration-env "$DECL" "$LIMITKEY")
: "${LIMIT_MIB:?}" "${DECLARATION_SHA256:?}"

mkdir -p "$OUT/final" "$OUT/last_sampled"
STATUS="$OUT/final/status.env"
CID=""; CG=""; SAMPLER_PID=""; FINAL_DONE=0; CLEANED=0
READ_FAILURES=""; OPTIONAL_ABSENT=""
WORKLOAD_EXIT=""; CLIENT_TIMED_OUT=0; TERMINATED_CONFIRMED=0; HOLDER_ALIVE=0; FINALITY=unavailable; REASON="not collected"
STARTED=$(date +%s)

write_status() {
  {
    echo "finality=$FINALITY"; echo "reason=$REASON"; echo "workload_exit=$WORKLOAD_EXIT"; echo "client_timed_out=$CLIENT_TIMED_OUT"; echo "terminated_confirmed=$TERMINATED_CONFIRMED"
    echo "holder_alive=$HOLDER_ALIVE"; echo "container_id=$CID"; echo "name=$NAME"; echo "cgroup=$CG"; echo "declaration_sha256=$DECLARATION_SHA256"; echo "limit_mib=$LIMIT_MIB"
    echo "limit_key=$LIMITKEY"; echo "fresh_container=1"; echo "wall_seconds=$(( $(date +%s) - STARTED ))"; echo "read_failures=$READ_FAILURES"; echo "optional_absent=$OPTIONAL_ABSENT"
  } > "$STATUS"
}

# ---- headroom: a PRECONDITION on the host, not a redefinition of the declared limit ----
{ $FREE_CMD; } > "$OUT/host-free.txt" 2>&1 || true
AVAILABLE=$(awk '/^Mem:/ {print $7}' "$OUT/host-free.txt")
if [ -z "$AVAILABLE" ] || [ "$AVAILABLE" -lt $(( LIMIT_MIB + HOST_MARGIN_MIB )) ]; then
  REASON="headroom precondition not met: available ${AVAILABLE:-unknown} MiB, needed $(( LIMIT_MIB + HOST_MARGIN_MIB )) MiB (declared limit $LIMIT_MIB + margin $HOST_MARGIN_MIB); this instance size is not viable at the declared limit and the test does not start"
  write_status; echo "$REASON"; exit 4
fi

holder_running() { [ "$("$DOCKER" inspect -f '{{.State.Running}}' "$NAME" 2>/dev/null)" = "true" ]; }

find_cgroup() {
  local candidate
  for candidate in "$CGROUP_BASE/system.slice/docker-$CID.scope" "$CGROUP_BASE/docker/$CID"; do
    [ -d "$candidate" ] && { echo "$candidate"; return 0; }
  done
  return 1
}

sample_once() {
  local ts cur mem cpu procs swap pid
  ts=$(date +%s%3N)
  cur=$(cat "$CG/memory.current" 2>/dev/null) || cur=NA
  mem=$(awk '$1=="anon"{a=$2} $1=="file"{f=$2} $1=="shmem"{s=$2} END{print (a==""?"NA":a), (f==""?"NA":f), (s==""?"NA":s)}' "$CG/memory.stat" 2>/dev/null) || mem=""
  [ -n "$mem" ] || mem="NA NA NA"
  cpu=$(awk '$1=="usage_usec"{u=$2} $1=="nr_throttled"{t=$2} END{print (u==""?"NA":u), (t==""?"NA":t)}' "$CG/cpu.stat" 2>/dev/null) || cpu=""
  [ -n "$cpu" ] || cpu="NA NA"
  procs=$(wc -l < "$CG/cgroup.procs" 2>/dev/null) || procs=NA
  swap=$(cat "$CG/memory.swap.current" 2>/dev/null) || swap=NA
  echo "$ts ${cur:-NA} $mem $cpu ${procs:-NA} ${swap:-NA}" | tr -s ' ' >> "$OUT/samples.tsv"
  for pid in $(cat "$CG/cgroup.procs" 2>/dev/null); do
    ps -o ppid=,rss=,comm= -p "$pid" 2>/dev/null | awk -v ts="$ts" -v pid="$pid" 'NF>=3 {print ts, pid, $1, $2, $3}' >> "$OUT/procs.tsv"
  done
  for f in memory.peak memory.events memory.pressure memory.swap.events; do cp "$CG/$f" "$OUT/last_sampled/$f" 2>/dev/null || true; done   # the LAST sampled kernel values: a labelled substitute, never final
}

sampler() { while true; do sample_once; sleep "$SAMPLE_INTERVAL_S"; done; }

alive() { "$DOCKER" exec "$NAME" sh -c 'test -s /tmp/workload.pid && kill -0 "$(cat /tmp/workload.pid)" 2>/dev/null' >/dev/null 2>&1; }

procs_in_cgroup() { wc -l < "$CG/cgroup.procs" 2>/dev/null || echo 999; }

confirm_termination() {
  # the workload must be shown to be gone: still alive means terminate (TERM, grace, KILL); then only the holder may remain in cgroup.procs
  local waited=0
  if alive; then
    "$DOCKER" exec "$NAME" sh -c 'kill -TERM "$(cat /tmp/workload.pid)" 2>/dev/null; true' >/dev/null 2>&1
    while [ "$waited" -lt "${GRACE_S:-20}" ] && alive; do sleep 1; waited=$(( waited + 1 )); done
    if alive; then "$DOCKER" exec "$NAME" sh -c 'kill -KILL "$(cat /tmp/workload.pid)" 2>/dev/null; true' >/dev/null 2>&1; sleep 1; fi
  fi
  if alive; then TERMINATED_CONFIRMED=0; return; fi
  [ -n "$CG" ] && [ "$(procs_in_cgroup)" -le 1 ] && TERMINATED_CONFIRMED=1 || TERMINATED_CONFIRMED=0
}

collect_final() {
  [ "$FINAL_DONE" = "1" ] && return
  FINAL_DONE=1
  [ -n "$SAMPLER_PID" ] && kill "$SAMPLER_PID" 2>/dev/null
  if [ -z "$CID" ]; then FINALITY=unavailable; REASON="the container never started"; write_status; return; fi
  if holder_running; then HOLDER_ALIVE=1; else HOLDER_ALIVE=0; fi
  if [ "$HOLDER_ALIVE" = "1" ]; then confirm_termination; fi
  # REV 4.1 B4: the REQUIRED final reads (the memory counters AND the enforced limits) and the optional ones. Every required failure is NAMED in status.env (read_failures) and makes the finality last_sampled
  # with the reason final_metrics_missing; an optional file that is absent is recorded as absent (optional_absent), never as 0.
  local f
  READ_FAILURES=""; OPTIONAL_ABSENT=""
  if [ -n "$CG" ] && [ -d "$CG" ]; then
    for f in memory.peak memory.events memory.max memory.swap.max cpu.max cpuset.cpus.effective; do cp "$CG/$f" "$OUT/final/$f" 2>/dev/null || READ_FAILURES="$READ_FAILURES${READ_FAILURES:+,}$f"; done
    for f in memory.pressure memory.swap.events memory.swap.current; do cp "$CG/$f" "$OUT/final/$f" 2>/dev/null || OPTIONAL_ABSENT="$OPTIONAL_ABSENT${OPTIONAL_ABSENT:+,}$f"; done
  else
    READ_FAILURES="cgroup"
  fi
  "$DOCKER" inspect "$NAME" > "$OUT/final/docker-inspect.json" 2>/dev/null || READ_FAILURES="$READ_FAILURES${READ_FAILURES:+,}docker-inspect"
  if [ "$HOLDER_ALIVE" != "1" ]; then FINALITY=last_sampled; REASON="final_metrics_missing: the holder or the cgroup died before the final read (an OOM kill, a stop or a daemon fault); the last sampled values are recorded beside it"; rm -f "$OUT/final/memory."* "$OUT/final/cpu.max" "$OUT/final/cpuset.cpus.effective"
  elif [ -n "$READ_FAILURES" ]; then FINALITY=last_sampled; REASON="final_metrics_missing: required reads failed: $READ_FAILURES"
  elif [ "$TERMINATED_CONFIRMED" != "1" ]; then FINALITY=last_sampled; REASON="final_metrics_missing: the workload could not be confirmed terminated, so the values are not final"
  else FINALITY=final_confirmed; REASON="read while the container was alive, after the workload was confirmed terminated"
  fi
  write_status
}

cleanup() {
  [ "$CLEANED" = "1" ] && return
  CLEANED=1
  collect_final                                   # BEFORE the container is removed: on success, on failure and after an interrupt
  [ -n "$CID" ] && "$DOCKER" rm -f "$NAME" >/dev/null 2>&1
}
trap cleanup EXIT INT TERM HUP

# ---- the fresh container, then the cgroup ----
CID=$("$DOCKER" run -d --name "$NAME" --cpus "$CPUS" --cpuset-cpus "$CPUSET" --memory "${LIMIT_MIB}m" --memory-swap "${SWAP_MIB}m" \
      -e "MAX_JOBS=$MAX_JOBS" -e "OMP_NUM_THREADS=$OMP_NUM_THREADS" -e "MKL_NUM_THREADS=$MKL_NUM_THREADS" -e "OPENBLAS_NUM_THREADS=$OPENBLAS_NUM_THREADS" \
      -e "TORCHINDUCTOR_COMPILE_THREADS=$TORCHINDUCTOR_COMPILE_THREADS" ${DOCKER_EXTRA_ARGS:-} "$IMAGE" sleep infinity) || { CID=""; REASON="docker run failed"; write_status; exit 5; }
CG=$(find_cgroup) || { CG=""; REASON="cgroup of the container not found under $CGROUP_BASE (cgroup v2 expected)"; }
if holder_running; then HOLDER_ALIVE=1; fi
# REV 4.1 B3: the limits that are ACTUALLY enforced, read BEFORE the workload (the declaration only proves what was declared): the cgroup files and docker's HostConfig; the final read repeats them
mkdir -p "$OUT/limits/start"
if [ -n "$CG" ]; then for f in memory.max memory.swap.max cpu.max cpuset.cpus.effective; do cp "$CG/$f" "$OUT/limits/start/$f" 2>/dev/null || true; done; fi
"$DOCKER" inspect "$NAME" > "$OUT/limits/docker-inspect-start.json" 2>/dev/null || true
: > "$OUT/samples.tsv"; : > "$OUT/procs.tsv"
if [ -n "$CG" ]; then sampler & SAMPLER_PID=$!; fi

# ---- the workload, through docker exec, with a client timeout that is NOT taken for the end of the workload ----
timeout "$TIMEOUT_S" "$DOCKER" exec "$NAME" sh -c 'echo $$ > /tmp/workload.pid; exec "$@"' sh "${WORKLOAD[@]}"
WORKLOAD_EXIT=$?
if [ "$WORKLOAD_EXIT" = "124" ]; then CLIENT_TIMED_OUT=1; fi
echo "workload exit $WORKLOAD_EXIT (client timed out: $CLIENT_TIMED_OUT)"
cleanup
exit "$WORKLOAD_EXIT"
